/** Obsidian keeps the UI language in localStorage ('ru', 'de', …; missing = English). */
function language(): string {
  try { return window.localStorage.getItem('language') ?? 'en'; } catch { return 'en'; }
}

/** Keys are the English strings; `{name}` placeholders are filled from `vars`. Missing translation falls back to English. */
export function t(key: string, vars: Record<string, string | number> = {}): string {
  const s = (language().startsWith('ru') ? ru[key] : undefined) ?? key;
  return s.replace(/\{(\w+)\}/g, (m, k) => k in vars ? String(vars[k]) : m);
}

